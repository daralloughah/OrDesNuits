const BAG = "odn.quotes.bag";
export function nextQuote() {
  let bag = [];
  try { bag = JSON.parse(localStorage.getItem(BAG)) || []; } catch {}
  bag = bag.filter((i) => i < QUOTES.length);
  if (!bag.length) { bag = QUOTES.map((_, i) => i); for (let i = bag.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [bag[i], bag[j]] = [bag[j], bag[i]]; } }
  const i = bag.shift();
  try { localStorage.setItem(BAG, JSON.stringify(bag)); } catch {}
  const [text, author, attr] = QUOTES[i];
  return { text, author, attr: !!attr, n: i + 1 };
}
